import { expect, test, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { expectHydrated } from '../support/hydration'

async function login(page: Page) {
  await page.goto('/admin/login')
  await expectHydrated(page)
  await page.getByTestId('username').fill('gavin')
  await page.getByTestId('password').fill('correct-horse')
  await page.getByTestId('login').click()
  await expect(page).toHaveURL(/\/admin\/articles$/)
}

test('password form verifies errors confirmation and success', async ({ page }) => {
  await login(page)
  await page.route('**/api/v1/auth/account', route => route.fulfill({ json: { username: 'gavin', email_masked: 'g***@163.com', mail_available: true } }))
  await page.goto('/admin/account')
  await page.getByLabel('当前密码', { exact: true }).fill('correct-horse')
  await page.route('**/api/v1/auth/account/code', route => route.fulfill({ status: 503, json: { detail: 'mail_unavailable' } }))
  await page.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('邮件暂不可用')
  await expect(page.getByRole('button', { name: '修改密码', exact: true })).toBeDisabled()
  await page.unroute('**/api/v1/auth/account/code')
  await page.route('**/api/v1/auth/account/code', route => route.fulfill({ status: 202, json: { challenge_id: 'test-only-challenge', expires_in: 600, retry_after: 60 } }))
  await page.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已提交发送' })).toBeVisible()
  await expect(page.getByRole('button', { name: /秒后重发/ })).toBeDisabled()
  await page.getByLabel('新密码', { exact: true }).fill('a-test-password-2026')
  await page.getByLabel('确认新密码', { exact: true }).fill('a-different-password')
  await page.getByLabel('邮箱验证码').fill('123456')
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('两次新密码输入不一致。')
  await page.getByLabel('确认新密码', { exact: true }).fill('a-test-password-2026')
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.route('**/api/v1/auth/account/password', route => route.fulfill({ status: 400, json: { detail: 'invalid_code' } }))
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await page.getByRole('button', { name: '确认更新密码', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('验证码错误')
  await expect(page.getByLabel('新密码', { exact: true })).toHaveValue('a-test-password-2026')
  await page.unroute('**/api/v1/auth/account/password')
  await page.route('**/api/v1/auth/account/password', async (route) => {
    expect(route.request().postDataJSON()).toEqual({ current_password: 'correct-horse', new_password: 'a-test-password-2026', challenge_id: 'test-only-challenge', code: '123456' })
    await route.fulfill({ status: 204 })
  })
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await page.getByRole('button', { name: '确认更新密码', exact: true }).click()
  await expect(page).toHaveURL(/reason=password-updated/)
  await expect(page.getByTestId('password')).toHaveValue('')
})

